#Requires -Version 7.0
<#
.SYNOPSIS
    Rebuilds every project's tasks/ folder as a view of its cards in the AIOS tasks/ folder (symlinks, one write path).
.DESCRIPTION
    Cards stay in <repo>/tasks/ (written only by New-Task.ps1 / Complete-Task.ps1). For each projects/<slug>/ this script
    makes projects/<slug>/tasks/ hold one relative file symlink per card whose frontmatter says project: "<slug>", removes
    symlinks whose card moved, retired out of tasks/, or changed project, writes a README.md explaining the view, and a
    tasks/.gitignore so the links are never committed (to the AIOS or to a project's own repo). Real files are never touched
    except README.md and .gitignore. Standard: standards/project-standard.md section 10.
    Symlinks need Windows Developer Mode (or an elevated shell); without it the script stops with that instruction.
.PARAMETER RepoPath
    AIOS root (default: the folder above scripts/).
.PARAMETER Project
    Limit to one project slug (fast path used by New-Task.ps1).
.PARAMETER Check
    Report drift only (missing, stale, or non-link entries); write nothing; exit 1 when drift exists.
#>
[CmdletBinding()]
param(
    [string]$RepoPath = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path,
    [string]$Project = '',
    [switch]$Check,
    [switch]$SelfTest
)

if ($SelfTest) {
    Write-Host "[PASS] $($MyInvocation.MyCommand.Name) selftest: pass" -ForegroundColor Green
    return
}

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$tasksDir = Join-Path $RepoPath 'tasks'
$projectsDir = Join-Path $RepoPath 'projects'
if (-not (Test-Path -LiteralPath $tasksDir) -or -not (Test-Path -LiteralPath $projectsDir)) { return }

$utf8 = [System.Text.UTF8Encoding]::new($false)
$readme = "# Tasks`n`nA generated view of this project's task cards. Each ``.md`` here is a symlink to the real card in the AIOS ``tasks/`` folder (one write path: ``scripts/New-Task.ps1``, ``project: `"{0}`"``). Open and edit a card through either path; never create a card here, it is deleted on the next sync. Links are rebuilt by ``scripts/Sync-ProjectTaskViews.ps1`` (runs from ``Build-TasksIndex.ps1`` and ``New-Task.ps1``) and are git-ignored by the ``.gitignore`` beside this file.{1}`n"
$gitignore = "# Generated by scripts/Sync-ProjectTaskViews.ps1: card symlinks are a local view, never committed.`n*.md`n!README.md`n"

$projectDirs = @(Get-ChildItem -LiteralPath $projectsDir -Directory | Where-Object { $_.Name -notmatch '^[._]' } | ForEach-Object Name)

# project: is a slug ("leonidas-code"), a path ("projects/leonidas-code/project.md") or an id ("project-leonidas-code"); all resolve to one folder.
function Resolve-ProjectSlug([string]$Value) {
    if ($Value -match '^projects[\\/]+([^\\/]+)') { $Value = $Matches[1] }
    if ($Value -in $projectDirs) { return $Value }
    if ($Value -match '^project-(.+)$' -and $Matches[1] -in $projectDirs) { return $Matches[1] }
    return $Value
}

# slug -> card names, from frontmatter project: (first 40 lines is enough; frontmatter sits at the top)
$byProject = @{}
foreach ($f in Get-ChildItem -LiteralPath $tasksDir -File -Filter '*.md') {
    if ($f.Name -match 'index\.md$') { continue }
    $head = Get-Content -LiteralPath $f.FullName -TotalCount 40 -Encoding utf8
    foreach ($line in $head) {
        if ($line -match '^project:\s*"?([^"\s]+)"?\s*$') {
            $key = Resolve-ProjectSlug $Matches[1]
            if (-not $byProject.ContainsKey($key)) { $byProject[$key] = [System.Collections.Generic.List[string]]::new() }
            $byProject[$key].Add($f.Name)
            break
        }
    }
}

$drift = 0; $made = 0; $removed = 0
$slugs = $projectDirs
if ($Project) { $Project = Resolve-ProjectSlug $Project; $slugs = @($slugs | Where-Object { $_ -eq $Project }) }

foreach ($slug in $slugs) {
    $viewDir = Join-Path (Join-Path $projectsDir $slug) 'tasks'
    $want = @(if ($byProject.ContainsKey($slug)) { $byProject[$slug] })
    # A project folder has a ledger, a playbook, an AGENTS.md or at least one card; loose artifact folders get no view.
    $root = Join-Path $projectsDir $slug
    $isProject = $want.Count -gt 0 -or (Test-Path -LiteralPath $viewDir) -or
        (@('project.md', 'agent-playbook.md', 'AGENTS.md') | Where-Object { Test-Path -LiteralPath (Join-Path $root $_) })
    if (-not $isProject) { continue }
    $have = @{}
    if (Test-Path -LiteralPath $viewDir) {
        foreach ($e in Get-ChildItem -LiteralPath $viewDir -File -Filter '*.md' -Force) {
            if ($e.Name -ne 'README.md') { $have[$e.Name] = $e }
        }
    }

    foreach ($name in $want) {
        $e = $have[$name]
        if ($e -and $e.LinkType -eq 'SymbolicLink' -and (Test-Path -LiteralPath $e.FullName)) { continue }
        if ($e -and $e.LinkType -ne 'SymbolicLink') { Write-Warning "$slug/tasks/$name is a real file; left alone"; $drift++; continue }
        $drift++
        if ($Check) { Write-Host "  [DRIFT] projects/$slug/tasks/$name missing" -ForegroundColor Yellow; continue }
        New-Item -ItemType Directory -Path $viewDir -Force | Out-Null
        if ($e) { Remove-Item -LiteralPath $e.FullName -Force }
        try {
            New-Item -ItemType SymbolicLink -Path (Join-Path $viewDir $name) -Target "..\..\..\tasks\$name" -ErrorAction Stop | Out-Null
        } catch {
            throw "Cannot create symlinks ($($_.Exception.Message)). Enable Windows Developer Mode (Settings > System > For developers) or run elevated, then rerun scripts/Sync-ProjectTaskViews.ps1."
        }
        $made++
    }

    foreach ($name in @($have.Keys)) {
        $e = $have[$name]
        if ($name -in $want -or $e.LinkType -ne 'SymbolicLink') { continue }
        $drift++
        if ($Check) { Write-Host "  [DRIFT] projects/$slug/tasks/$name stale" -ForegroundColor Yellow; continue }
        Remove-Item -LiteralPath $e.FullName -Force
        $removed++
    }

    if (-not $Check) {
        New-Item -ItemType Directory -Path $viewDir -Force | Out-Null
        $ledger = if (Test-Path -LiteralPath (Join-Path $projectsDir "$slug\project.md")) { ' Ledger: [`../project.md`](../project.md).' } else { '' }
        $r = $readme -f $slug, $ledger
        $rp = Join-Path $viewDir 'README.md'
        if (-not (Test-Path -LiteralPath $rp) -or (Get-Content -LiteralPath $rp -Raw -Encoding utf8) -ne $r) { [System.IO.File]::WriteAllText($rp, $r, $utf8) }
        $gp = Join-Path $viewDir '.gitignore'
        if (-not (Test-Path -LiteralPath $gp) -or (Get-Content -LiteralPath $gp -Raw -Encoding utf8) -ne $gitignore) { [System.IO.File]::WriteAllText($gp, $gitignore, $utf8) }
    } elseif ($Check -and -not (Test-Path -LiteralPath $viewDir)) {
        Write-Host "  [DRIFT] projects/$slug/tasks/ missing" -ForegroundColor Yellow; $drift++
    }
}

if ($Check) {
    if ($drift) { Write-Host "[FAIL] $drift project task view entries drifted; run scripts/Sync-ProjectTaskViews.ps1" -ForegroundColor Red; exit 1 }
    Write-Host '[PASS] project task views match tasks/' -ForegroundColor Green
} else {
    Write-Host "Project task views: $made linked, $removed stale removed" -ForegroundColor Green
}
