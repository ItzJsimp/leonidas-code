<#
.SYNOPSIS
  Generates engine instruction adapters (CLAUDE.md, GEMINI.md, .cursor/rules/leonidas.mdc) from AGENTS.md.
.DESCRIPTION
  AGENTS.md is the single source. Claude follows @imports; Gemini and Cursor get AGENTS.md with
  @LEONIDAS.md inlined. -Check exits 1 when any adapter is stale, without writing.
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$header = '<!-- generated by scripts/Build-AgentAdapters.ps1 from AGENTS.md; do not edit -->'

$agents = (Get-Content -Raw -LiteralPath (Join-Path $root 'AGENTS.md')) -replace "`r`n", "`n"
$brief = (Get-Content -Raw -LiteralPath (Join-Path $root 'LEONIDAS.md')) -replace "`r`n", "`n"
$inlined = $agents -replace '(?m)^@LEONIDAS\.md\s*$', $brief.TrimEnd()

$claude = @"
$header
@AGENTS.md
<!-- Operator AIOS fallback: resolves when this repo sits at <AIOS>/projects/leonidas-code; ignored otherwise. -->
@../../CLAUDE.md
"@

$cursor = @"
---
description: Leonidas Code agent router (generated from AGENTS.md)
alwaysApply: true
---
$header

$inlined
"@

$targets = [ordered]@{
  'CLAUDE.md'                   = $claude
  'GEMINI.md'                   = "$header`n`n$inlined"
  '.cursor/rules/leonidas.mdc'  = $cursor
}

$stale = @()
foreach ($rel in $targets.Keys) {
  $path = Join-Path $root $rel
  $want = ($targets[$rel] -replace "`r`n", "`n").TrimEnd() + "`n"
  $have = if (Test-Path -LiteralPath $path) { (Get-Content -Raw -LiteralPath $path) -replace "`r`n", "`n" } else { '' }
  if ($have -ceq $want) { continue }
  $stale += $rel
  if (-not $Check) { [IO.File]::WriteAllText($path, $want, [Text.UTF8Encoding]::new($false)) }
}

if ($Check) {
  if ($stale) { Write-Output "[FAIL] stale adapters: $($stale -join ', '). Run scripts/Build-AgentAdapters.ps1"; exit 1 }
  Write-Output '[PASS] adapters match AGENTS.md'
} else {
  Write-Output "[OK] wrote $($stale.Count) adapter(s)$(if ($stale) { ': ' + ($stale -join ', ') })"
}
